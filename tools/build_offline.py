#!/usr/bin/env python3
"""Regenerate offline.js, which lets index.html run straight from disk (file://).

Browsers block two things on file:// pages: fetch() of local files, and new Worker('worker.js').
offline.js works around both without a server:
  * the worker source (core.js + worker.js) is embedded as a string and started from a Blob URL;
  * the sample photo and the examples are embedded as base64.
The page always uses these embedded copies, so it behaves the same from disk, from a local server,
or through an HTML preview proxy that cannot serve worker.js next to the page.

Run this after editing core.js, worker.js, the sample photo or examples/*.json:
    python3 tools/build_offline.py
Only the Python standard library is needed."""
import base64, json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent

def b64(path): return base64.b64encode((ROOT / path).read_bytes()).decode()

core = (ROOT / "core.js").read_text()
worker = (ROOT / "worker.js").read_text()
worker, n = re.subn(r"^importScripts\('core\.js'\);\s*$", "", worker, flags=re.M)
assert n == 1, "worker.js should contain exactly one importScripts('core.js') line"
worker_src = core + "\n;\n" + worker

photos, examples = {}, {}
for p in sorted((ROOT / "examples").glob("*.json")):
    x = json.loads(p.read_text())
    photos.setdefault(x["photo"], b64(x["photo"]))
    examples[x["id"]] = x
sample = "sample-einstein.jpg"
photos.setdefault(sample, b64(sample))

js = f"""/* GENERATED by tools/build_offline.py. Do not edit; edit core.js, worker.js or examples/ and rerun it.
   Lets index.html work when opened directly from disk (file://), where browsers block fetch() and
   new Worker('worker.js'): the worker (core.js + worker.js) and the sample photo are embedded here. */
(function () {{
  'use strict';
  const WORKER_SRC = {json.dumps(worker_src)};
  const PHOTOS = {json.dumps(photos)};
  const EXAMPLES = {json.dumps(examples)};
  let workerURL = null;
  function blobOf(name) {{
    const bin = atob(PHOTOS[name]), u = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) u[i] = bin.charCodeAt(i);
    return new Blob([u], {{ type: /\\.png$/i.test(name) ? 'image/png' : 'image/jpeg' }});
  }}
  window.SAOffline = {{
    worker() {{
      if (!workerURL) workerURL = URL.createObjectURL(new Blob([WORKER_SRC], {{ type: 'text/javascript' }}));
      return new Worker(workerURL);
    }},
    sampleBlob() {{ return Promise.resolve(blobOf({json.dumps(sample)})); }},
    example(id) {{
      const x = EXAMPLES[id];
      if (!x) return Promise.reject(new Error('no example ' + id));
      return Promise.resolve({{ x: JSON.parse(JSON.stringify(x)), blob: blobOf(x.photo) }});
    }}
  }};
}})();
"""
(ROOT / "offline.js").write_text(js)
print(f"offline.js written: {len(js) / 1024:.0f} KB, examples: {', '.join(examples)}")
